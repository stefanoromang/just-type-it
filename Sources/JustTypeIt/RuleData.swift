import Foundation

/// A pattern rule: a regex, its replacement template, and how to describe it.
struct PatternRule {
    var pattern: String
    var replacement: String
    var group: IssueGroup
    var kind: String
    var title: String
    var explanation: String
    var caseInsensitive = true
}

enum RuleData {

    static let grammar: [PatternRule] = [
        // Contextual spelling / confused words
        PatternRule(pattern: "\\b(their|there) (is|are|was|were|going|coming|not)\\b(?<!there (is|are|was|were|not))", replacement: "they're $2",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Confused word",
                    explanation: "Use “they're” (they are) before a verb like “going”."),
        PatternRule(pattern: "\\btheir (is|are|was|were)\\b", replacement: "there $1",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Confused word",
                    explanation: "“There is/are” points to existence; “their” shows possession."),
        PatternRule(pattern: "\\b(they're|there) (car|house|home|own|family|friends|work|job|team|names?|books?|dog|cat|kids|children|parents|money|phone|office|idea|ideas|way|time)\\b", replacement: "their $2",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Confused word",
                    explanation: "Use the possessive “their” before a noun that belongs to them."),
        PatternRule(pattern: "\\byour (welcome|right|wrong|going|coming|being|not|so|very|the best|doing)\\b", replacement: "you're $1",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Confused word",
                    explanation: "“You're” is the contraction of “you are”; “your” shows possession."),
        PatternRule(pattern: "\\bits (a|an|the|been|not|going|very|so|time|important|clear|true|likely|possible|hard|easy)\\b", replacement: "it's $1",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Confused word",
                    explanation: "“It's” means “it is” or “it has”; “its” is possessive."),
        PatternRule(pattern: "\\bit's (own|self)\\b", replacement: "its $1",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Confused word",
                    explanation: "Use the possessive “its” (no apostrophe)."),
        PatternRule(pattern: "\\b(the|an|positive|negative|big|huge|significant|an?) affect\\b", replacement: "$1 effect",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Affect vs. effect",
                    explanation: "“Effect” is usually the noun (a result); “affect” is usually the verb (to influence)."),
        PatternRule(pattern: "\\b(will|can|could|would|may|might|does|did|to) effect (the|my|your|his|her|our|their|us|them|you|him)\\b", replacement: "$1 affect $2",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Affect vs. effect",
                    explanation: "“Affect” is the verb meaning to influence."),
        PatternRule(pattern: "\\b(more|less|better|worse|bigger|smaller|faster|slower|rather|other|greater|higher|lower) then\\b", replacement: "$1 than",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Then vs. than",
                    explanation: "Use “than” for comparisons; “then” refers to time."),
        PatternRule(pattern: "\\b(could|would|should|must|might) of\\b", replacement: "$1 have",
                    group: .correctness, kind: "Grammar/ModalOf", title: "Incorrect verb form",
                    explanation: "“Could of” is a mishearing of “could've” — write “could have”."),
        PatternRule(pattern: "\\b(lose|loose)(?= (fitting|clothes|shirt|pants|screw|ends|change))", replacement: "loose",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Lose vs. loose",
                    explanation: "“Loose” means not tight; “lose” means to misplace or fail to win."),
        PatternRule(pattern: "\\b(will|to|don't|didn't|not|never) loose\\b", replacement: "$1 lose",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Lose vs. loose",
                    explanation: "“Lose” is the verb (to misplace, to be defeated)."),
        PatternRule(pattern: "\\balot\\b", replacement: "a lot",
                    group: .correctness, kind: "Spelling/Misspelled", title: "Misspelling",
                    explanation: "“A lot” is always two words."),
        PatternRule(pattern: "\\bwho's (car|house|book|idea|turn|phone|job|fault)\\b", replacement: "whose $1",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "Who's vs. whose",
                    explanation: "“Whose” is possessive; “who's” means “who is”."),
        PatternRule(pattern: "\\bto (much|many|late|early|soon|big|small|long|far|hard|fast)\\b", replacement: "too $1",
                    group: .correctness, kind: "Spelling/AccidentallyConfused", title: "To vs. too",
                    explanation: "“Too” means excessively or also."),
        PatternRule(pattern: "\\b(i|we|they|you) was\\b", replacement: "$1 were",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "Use “were” with I (in some moods), we, you and they. With “I”, “was” is correct in the indicative — check your meaning."),
        PatternRule(pattern: "\\b(he|she|it) (don't)\\b", replacement: "$1 doesn't",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "Third-person singular subjects take “doesn't”."),
        PatternRule(pattern: "\\b(he|she|it) (dont)\\b", replacement: "$1 doesn't",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "Third-person singular subjects take “doesn't”."),
        PatternRule(pattern: "\\b(he|she|it) (have)\\b", replacement: "$1 has",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "Third-person singular subjects take “has”."),
        PatternRule(pattern: "\\b(i|you|we|they) (has)\\b", replacement: "$1 have",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "Use “have” with I, you, we and they."),
        PatternRule(pattern: "\\b(he|she|it) (go|do|want|need|like|say|think|know|make|take|come|see|get|work|try|seem|feel|look)\\b(?<!(?:make|makes|made|let|lets|help|helps|watch|saw|see|have|has|had|does|did|do|will|would|can|could|should|may|might|must|to|why|not) (?:he|she|it) \\w{1,5})", replacement: "$1 $2s",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "A singular subject (he, she, it) needs a verb ending in -s."),
        PatternRule(pattern: "\\b(they|we|you|i) (is)\\b", replacement: "$1 are",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "Plural subjects take “are”."),
        PatternRule(pattern: "\\b(there|here) is (two|three|four|five|six|seven|eight|nine|ten|many|several|some|lots|a lot of|a few) ", replacement: "$1 are $2 ",
                    group: .correctness, kind: "Grammar/SubjectVerbAgreement", title: "Subject-verb agreement",
                    explanation: "The subject that follows is plural, so use “are”."),
        PatternRule(pattern: "\\b(me and (him|her|them)|(him|her|them) and me) (was|were|are|went|go|did|have|had|will)\\b", replacement: "",
                    group: .correctness, kind: "Grammar/PronounCase", title: "Pronoun case",
                    explanation: "Use subject pronouns (I, he, she, they) as the subject of a verb, and put “I” last."),
        PatternRule(pattern: "^(me and (\\w+)) (was|were|are|went|go|did|have|had|will)\\b", replacement: "$2 and I $3",
                    group: .correctness, kind: "Grammar/PronounCase", title: "Pronoun case",
                    explanation: "Use “I” as the subject of a verb, and mention yourself last."),
        PatternRule(pattern: "\\bbetween you and I\\b", replacement: "between you and me",
                    group: .correctness, kind: "Grammar/PronounCase", title: "Pronoun case",
                    explanation: "After a preposition like “between”, use the object pronoun “me”."),
        PatternRule(pattern: "\\b(to|for|with) (who)\\b(?! (is|are|was|were))", replacement: "$1 whom",
                    group: .correctness, kind: "Grammar/WhoWhom", title: "Who vs. whom",
                    explanation: "After a preposition, use the object form “whom”."),
        PatternRule(pattern: "\\b(less) (people|items|things|cars|books|mistakes|errors|calories|words|hours|days|students|employees)\\b", replacement: "fewer $2",
                    group: .correctness, kind: "Grammar/FewerLess", title: "Fewer vs. less",
                    explanation: "Use “fewer” for things you can count."),
        PatternRule(pattern: "\\b(a) (?=[aeiou](?!ni|ur|se|ser|sual|sing|tensil|topia|ro|kr|ne |nique|nit|niv|nif))(\\w+)", replacement: "an $2",
                    group: .correctness, kind: "Grammar/Articles", title: "Article",
                    explanation: "Use “an” before a vowel sound."),
        PatternRule(pattern: "\\b(a) (?=hour|honest|honor|honour|heir)(\\w+)", replacement: "an $2",
                    group: .correctness, kind: "Grammar/Articles", title: "Article",
                    explanation: "Use “an” before a silent “h”."),
        PatternRule(pattern: "\\b(an) (?=[bcdfgjklmnpqrstvwxz]|uni|use|usu|euro|one\\b)(\\w+)", replacement: "a $2",
                    group: .correctness, kind: "Grammar/Articles", title: "Article",
                    explanation: "Use “a” before a consonant sound."),
        PatternRule(pattern: "\\b(yesterday|last (week|month|year|night)|ago)\\b[^.!?]*?\\b(he|she|it|i|we|they|you) (go|eat|see|come|run|buy|write|take|give|make|do)\\b", replacement: "",
                    group: .correctness, kind: "Grammar/VerbTense", title: "Verb tense",
                    explanation: "A past-time phrase needs a past-tense verb."),
        PatternRule(pattern: "\\b(he|she|it|i|we|they|you) (go|eat|see|come|run|buy|write|take|give|make|do) ([^.!?]*?)\\b(yesterday|last (week|month|year|night))\\b", replacement: "",
                    group: .correctness, kind: "Grammar/VerbTense", title: "Verb tense",
                    explanation: "A past-time phrase needs a past-tense verb."),
        PatternRule(pattern: "\\b((?:discuss|emphasiz|emphasis|mention|describ|explain|consider)\\w*) about\\b", replacement: "$1",
                    group: .correctness, kind: "Grammar/Preposition", title: "Unnecessary preposition",
                    explanation: "This verb takes a direct object; drop “about”."),
        PatternRule(pattern: "\\bdepend(s|ed|ing)? of\\b", replacement: "depend$1 on",
                    group: .correctness, kind: "Grammar/Preposition", title: "Preposition",
                    explanation: "The idiom is “depend on”."),
        PatternRule(pattern: "\\b(interested|good|bad) on\\b", replacement: "$1 in",
                    group: .correctness, kind: "Grammar/Preposition", title: "Preposition",
                    explanation: "Use “in” with this adjective."),
        PatternRule(pattern: "\\bmarried with\\b", replacement: "married to",
                    group: .correctness, kind: "Grammar/Preposition", title: "Preposition",
                    explanation: "The idiom is “married to”."),
        PatternRule(pattern: "\\b(arrive|arrived|arriving) to\\b", replacement: "$1 at",
                    group: .correctness, kind: "Grammar/Preposition", title: "Preposition",
                    explanation: "You arrive “at” a place (or “in” a city)."),
        PatternRule(pattern: "\\bdifferent then\\b", replacement: "different from",
                    group: .correctness, kind: "Grammar/Preposition", title: "Preposition",
                    explanation: "The standard phrase is “different from”."),
        PatternRule(pattern: "\\b(should|could|would|must|can|will|might) (went|gone|ate|wrote|took|gave|saw|did|was|has)\\b", replacement: "",
                    group: .correctness, kind: "Grammar/VerbForm", title: "Verb form",
                    explanation: "A modal verb (should, could, will…) is followed by the base form of the verb."),
        PatternRule(pattern: "\\bi\\b", replacement: "I",
                    group: .correctness, kind: "Grammar/Capitalization", title: "Capitalization",
                    explanation: "The pronoun “I” is always capitalized.", caseInsensitive: false),
        PatternRule(pattern: "(?<!\\b(?:he|she|it) )\\b(dont|cant|wont|didnt|doesnt|isnt|wasnt|arent|werent|shouldnt|couldnt|wouldnt|havent|hasnt|im|ive|youre|theyre|thats|whats|lets go)\\b", replacement: "",
                    group: .correctness, kind: "Punctuation/Apostrophe", title: "Missing apostrophe",
                    explanation: "Contractions need an apostrophe where letters are left out."),
    ]
}
